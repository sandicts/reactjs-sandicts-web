import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  activeBrandVariant,
  activeBrandVariantId,
  brandVariants,
} from "../src/config/brand.ts";
import { brandArtworks } from "../src/lib/brand/brand-artwork.ts";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, "..");
const checkOnly = process.argv.includes("--check");
const require = createRequire(import.meta.url);
const brandFontSourcePath =
  require.resolve("@fontsource/roboto/files/roboto-latin-500-normal.woff");
const brandFontTargetPath = resolve(
  projectRoot,
  "public/fonts/roboto-latin-500-normal.woff",
);

const generatedTargets = [
  {
    contents: renderVariantCss(),
    label: "runtime brand tokens",
    path: resolve(projectRoot, "src/app/brand-variants.generated.css"),
  },
  {
    contents: renderVariantCss(),
    label: "prototype brand tokens",
    path: resolve(
      projectRoot,
      "docs/frontend/prototypes/shared/sandicts-brand-tokens.css",
    ),
  },
  {
    contents: renderBrandSvg({ includeMetadata: true }),
    label: "public brand mark",
    path: resolve(projectRoot, "public/sandicts-mark.svg"),
  },
  {
    contents: renderBrandSvg({ includeMetadata: false }),
    label: "application icon",
    path: resolve(projectRoot, "src/app/icon.svg"),
  },
];

function toCustomPropertyName(tokenName) {
  return tokenName.replace(
    /[A-Z]/g,
    (character) => `-${character.toLowerCase()}`,
  );
}

function renderTokenBlock(tokens) {
  return Object.entries(tokens)
    .filter(([tokenName]) => tokenName !== "static")
    .map(
      ([tokenName, value]) =>
        `  --${toCustomPropertyName(tokenName)}: ${value};`,
    )
    .join("\n");
}

function renderVariantCss() {
  const blocks = Object.values(brandVariants).flatMap((variant) => [
    `[data-brand-variant="${variant.id}"] {\n${renderTokenBlock(
      variant.theme.light,
    )}\n}`,
    [
      `.dark[data-brand-variant="${variant.id}"],`,
      `.dark [data-brand-variant="${variant.id}"] {`,
      renderTokenBlock(variant.theme.dark),
      "}",
    ].join("\n"),
    [
      `[data-brand-variant="${variant.id}"][data-brand-scheme="light"],`,
      `[data-brand-variant="${variant.id}"][data-brand-scheme="light"]`,
      `  [data-brand-variant="${variant.id}"] {`,
      renderTokenBlock(variant.theme.light),
      "}",
    ].join("\n"),
    [
      `[data-brand-variant="${variant.id}"][data-brand-scheme="dark"],`,
      `[data-brand-variant="${variant.id}"][data-brand-scheme="dark"]`,
      `  [data-brand-variant="${variant.id}"] {`,
      renderTokenBlock(variant.theme.dark),
      "}",
    ].join("\n"),
  ]);

  return `/*
 * Generated by scripts/sync-brand-system.mjs.
 * Edit src/config/brand.ts, then run npm run brand:sync.
 */
${blocks.join("\n\n")}
`;
}

function renderBrandSvg({ includeMetadata }) {
  const artwork = brandArtworks[activeBrandVariant.artworkId];
  const metadata = includeMetadata
    ? `\n  <metadata>Sandicts brand variant: ${activeBrandVariantId}</metadata>`
    : "";

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${artwork.viewBox}" role="img" style="color: ${activeBrandVariant.theme.static.brand}">
  <title>${activeBrandVariant.displayName}</title>${metadata}
  <path fill="currentColor" d="${artwork.path}"/>
</svg>
`;
}

async function syncTarget(target) {
  let current = "";

  try {
    current = await readFile(target.path, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") {
      throw error;
    }
  }

  if (current === target.contents) {
    return { ...target, changed: false };
  }

  if (!checkOnly) {
    await writeFile(target.path, target.contents, "utf8");
  }

  return { ...target, changed: true };
}

async function syncBrandFont() {
  const expected = await readFile(brandFontSourcePath);
  let current = Buffer.alloc(0);

  try {
    current = await readFile(brandFontTargetPath);
  } catch (error) {
    if (error?.code !== "ENOENT") {
      throw error;
    }
  }

  if (current.equals(expected)) {
    return false;
  }

  if (!checkOnly) {
    await mkdir(dirname(brandFontTargetPath), { recursive: true });
    await writeFile(brandFontTargetPath, expected);
  }

  return true;
}

for (const variant of Object.values(brandVariants)) {
  if (!(variant.artworkId in brandArtworks)) {
    throw new Error(
      `Brand variant "${variant.id}" references unknown artwork "${variant.artworkId}".`,
    );
  }
}

const [results, fontChanged] = await Promise.all([
  Promise.all(generatedTargets.map(syncTarget)),
  syncBrandFont(),
]);
const changed = results.filter((result) => result.changed);

if (fontChanged) {
  changed.push({
    changed: true,
    label: "Roboto brand font",
    path: brandFontTargetPath,
  });
}

if (checkOnly && changed.length > 0) {
  console.error(
    `Brand artifacts are out of sync: ${changed
      .map((target) => target.label)
      .join(", ")}. Run npm run brand:sync.`,
  );
  process.exitCode = 1;
} else if (changed.length === 0) {
  console.log("Brand artifacts are already in sync.");
} else {
  console.log(`Updated ${changed.map((target) => target.label).join(", ")}.`);
}
